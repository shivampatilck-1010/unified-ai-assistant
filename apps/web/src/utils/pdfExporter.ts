/**
 * Extracts a readable document title from markdown
 */
export function extractDocumentTitle(markdown: string): string | null {
  if (!markdown) return null;

  // Look for # Header
  const h1Match = markdown.match(/^#\s+(?:[^\n#]+)/m);
  if (h1Match) {
    return h1Match[0].replace(/^#\s+/, '').replace(/[📄📋📝*]/g, '').trim();
  }

  // Look for "Exam Preparation Guide" or "Study Guide"
  const guideMatch = markdown.match(/(?:[a-zA-Z0-9\s]+(?:Exam|Study|Revision|Reference)\s+(?:Guide|Paper|Notes|Cheat\s+Sheet))/i);
  if (guideMatch) {
    return guideMatch[0].trim();
  }

  return null;
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

/**
 * Converts markdown text into high-fidelity HTML with KaTeX formulas and clean tags
 */
function convertMarkdownToPrintHtml(markdown: string): string {
  // If the markdown is wrapped inside an outer code fence (e.g. ```markdown ... ```)
  let clean = markdown.trim();
  const outerFenceMatch = clean.match(/^```(?:markdown|text|md)?\s*\n([\s\S]+?)\n```$/i);
  if (outerFenceMatch) {
    clean = outerFenceMatch[1];
  }

  // Strip internal interactive simulation blocks for print document
  clean = clean.replace(/```(?:interactive-simulation|simulation|generative-ui)[\s\S]*?```/gi, '');
  clean = clean.replace(/<!--[\s\S]*?-->/g, '');

  const lines = clean.split('\n');
  const htmlParts: string[] = [];

  let inCode = false;
  let codeLang = '';
  let codeBuffer: string[] = [];

  let inList = false;
  let isOrdered = false;

  let inTable = false;
  let tableBuffer: string[] = [];

  const flushList = () => {
    if (inList) {
      htmlParts.push(isOrdered ? '</ol>' : '</ul>');
      inList = false;
    }
  };

  const flushTable = () => {
    if (tableBuffer.length >= 2) {
      const rows = tableBuffer.map((r) =>
        r.trim().replace(/^\|/, '').replace(/\|$/, '').split('|').map((c) => c.trim())
      );
      const header = rows[0];
      const body = rows.slice(2);

      let tableHtml = '<table><thead><tr>';
      header.forEach((h) => {
        tableHtml += `<th>${renderInline(h)}</th>`;
      });
      tableHtml += '</tr></thead><tbody>';
      body.forEach((row) => {
        tableHtml += '<tr>';
        row.forEach((c) => {
          tableHtml += `<td>${renderInline(c)}</td>`;
        });
        tableHtml += '</tr>';
      });
      tableHtml += '</tbody></table>';
      htmlParts.push(tableHtml);
    }
    tableBuffer = [];
    inTable = false;
  };

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const trimmed = line.trim();

    // Code block
    if (trimmed.startsWith('```')) {
      flushList();
      flushTable();
      if (!inCode) {
        inCode = true;
        codeLang = trimmed.slice(3).trim();
        codeBuffer = [];
      } else {
        inCode = false;
        htmlParts.push(`<pre><code class="language-${codeLang}">${escapeHtml(codeBuffer.join('\n'))}</code></pre>`);
        codeBuffer = [];
      }
      continue;
    }

    if (inCode) {
      codeBuffer.push(line);
      continue;
    }

    // Display Math: $$ ... $$ or \[ ... \]
    if (trimmed.startsWith('$$') || trimmed.startsWith('\\[')) {
      flushList();
      flushTable();
      const mathContent = trimmed
        .replace(/^\$\$/, '')
        .replace(/\$\$$/, '')
        .replace(/^\\\[/, '')
        .replace(/\\\]$/, '');
      try {
        const rendered = katex.renderToString(mathContent, { displayMode: true, throwOnError: false });
        htmlParts.push(rendered);
      } catch {
        htmlParts.push(`<div class="katex-display"><code>${escapeHtml(mathContent)}</code></div>`);
      }
      continue;
    }

    // Tables: | a | b |
    if (trimmed.startsWith('|') && trimmed.endsWith('|')) {
      flushList();
      inTable = true;
      tableBuffer.push(trimmed);
      continue;
    } else if (inTable) {
      flushTable();
    }

    // Headers
    if (trimmed.startsWith('#### ')) {
      flushList();
      htmlParts.push(`<h4>${renderInline(trimmed.slice(5))}</h4>`);
      continue;
    }
    if (trimmed.startsWith('### ')) {
      flushList();
      htmlParts.push(`<h3>${renderInline(trimmed.slice(4))}</h3>`);
      continue;
    }
    if (trimmed.startsWith('## ')) {
      flushList();
      htmlParts.push(`<h2>${renderInline(trimmed.slice(3))}</h2>`);
      continue;
    }
    if (trimmed.startsWith('# ')) {
      flushList();
      htmlParts.push(`<h1>${renderInline(trimmed.slice(2))}</h1>`);
      continue;
    }

    // Horizontal Rule
    if (/^---+$|^\*\*\*+$/.test(trimmed)) {
      flushList();
      htmlParts.push('<hr>');
      continue;
    }

    // Blockquote
    if (trimmed.startsWith('> ')) {
      flushList();
      htmlParts.push(`<blockquote>${renderInline(trimmed.slice(2))}</blockquote>`);
      continue;
    }

    // Lists
    const bullet = trimmed.match(/^[-*]\s+(.*)$/);
    if (bullet) {
      if (!inList || isOrdered) {
        flushList();
        htmlParts.push('<ul>');
        inList = true;
        isOrdered = false;
      }
      htmlParts.push(`<li>${renderInline(bullet[1])}</li>`);
      continue;
    }

    const ordered = trimmed.match(/^\d+\.\s+(.*)$/);
    if (ordered) {
      if (!inList || !isOrdered) {
        flushList();
        htmlParts.push('<ol>');
        inList = true;
        isOrdered = true;
      }
      htmlParts.push(`<li>${renderInline(ordered[1])}</li>`);
      continue;
    }

    flushList();

    if (trimmed === '') {
      continue;
    }

    // Paragraph
    htmlParts.push(`<p>${renderInline(trimmed)}</p>`);
  }

  flushList();
  flushTable();

  return htmlParts.join('\n');
}

/**
 * Renders inline formatting: bold, italic, inline math, inline code
 */
function renderInline(text: string): string {
  if (!text) return '';

  // 1. Render inline math $...$ or \( ... \)
  let out = text.replace(/(\\\([\s\S]+?\\\)|(?<!\$)\$(?!\$)(?:[^\$\n]|\\\$)+?(?<!\$)\$(?!\$))/g, (match) => {
    const rawMath = match.startsWith('\\(')
      ? match.slice(2, -2)
      : match.slice(1, -1);
    try {
      return katex.renderToString(rawMath, { displayMode: false, throwOnError: false });
    } catch {
      return `<code>${escapeHtml(rawMath)}</code>`;
    }
  });

  // 2. Inline code `code`
  out = out.replace(/`([^`]+)`/g, (_, code) => `<code>${escapeHtml(code)}</code>`);

  // 3. Bold **bold**
  out = out.replace(/\*\*([^*]+)\*\*/g, (_, bold) => `<strong>${bold}</strong>`);

  // 4. Italic *italic*
  out = out.replace(/\*([^*]+)\*/g, (_, it) => `<em>${it}</em>`);

  return out;
}
